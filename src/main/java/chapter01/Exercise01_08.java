package chapter01;

/**
 * A program that displays the area and perimeter of a circle that has a radius
 * of '5.5'
 *
 * @author emaph
 */
public class Exercise01_08 {

  public static void main(String[] args) {
    System.out.println("Area = " + 5.5 * 5.5 * 3.14159);
    System.out.println("Perimeter = " + 2.0 * 5.5 * 3.14159);
  }
}

/*
    Area = 95.0330975
    Perimeter = 34.55749
 */
