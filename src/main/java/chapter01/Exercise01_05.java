package chapter01;

/**
 * A program that displays the result of an expression
 *
 * @author emaph
 */
public class Exercise01_05 {

  public static void main(String[] args) {
    System.out.println("9.5 X 4.5 - 2.5 X 3");
    System.out.println("-------------------");
    System.out.println("     45.5 - 3.5");
    System.out.println("");
    System.out.println((9.5 * 4.5 - 2.5 * 3) / (45.5 - 3.5));
  }
}

/*
9.5 X 4.5 - 2.5 X 3
-------------------
     45.5 - 3.5

0.8392857142857143
 */
